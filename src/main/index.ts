/**
 * Application startup sequence with splash screen and first-run wizard
 */
async function startApplication(): Promise<void> {
  try {
    log("=== Pinguin Application Starting ===");

    // Register IPC handlers first
    registerErrorIPCHandlers();
    const ipcHandlers = IPCHandlers.getInstance();
    ipcHandlers.registerHandlers();

    // Create and show splash screen
    const splashWindow = new SplashWindow();
    const splash = splashWindow.create();

    // Initialize startup manager
    const startupManager = StartupManager.getInstance();
    startupManager.setSplashWindow(splash);

    // Execute startup sequence
    await startupManager.startup();

    // Get main window
    const mainWindow = startupManager.getMainWindow();

    // Close splash screen and show main window
    splashWindow.close();
    
    // Show main window (the React app will handle first-run wizard routing)
    if (mainWindow && !mainWindow.isVisible()) {
      mainWindow.show();
    }

    log("=== Pinguin Application Started ===");
  } catch (error: unknown) {
    const errorMessage = error instanceof Error ? error.message : String(error);
    log(`Application startup failed: ${errorMessage}`);
    
    // Show error dialog
    import("electron").then(({ dialog }) => {
      dialog.showErrorBox(
        "Startup Failed",
        `Pinguin failed to start:\n\n${errorMessage}\n\nPlease check the logs for more details.`
      );
      app.quit();
    }).catch(() => {
      // If dialog fails, just quit
      app.quit();
    });
  }
}

// This method will be called when Electron has finished
// initialization and is ready to create browser windows.
// Some APIs can only be used after this event occurs.
app.on("ready", () => {
  startApplication();
});

// Quit when all windows are closed, except on macOS. There, it's common
// for applications and their menu bar to stay active until the user quits
// explicitly with Cmd + Q.
app.on("window-all-closed", () => {
  if (process.platform !== "darwin") {
    app.quit();
  }
});

app.on("activate", () => {
  // On OS X it's common to re-create a window in the app when the
  // dock icon is clicked and there are no other windows open.
  const startupManager = StartupManager.getInstance();
  if (BrowserWindow.getAllWindows().length === 0 && startupManager.isReady()) {
    // If startup is complete but window was closed, just create a new window
    // This is a simplified approach - in production you might want to re-run startup
    log("Recreating window after activation");
  }
});

