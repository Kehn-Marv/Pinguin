/**
 * Graceful shutdown sequence
 */
let shutdownComplete = false;

app.on("before-quit", async (event) => {
  // If shutdown is already complete, allow quit
  if (shutdownComplete) {
    return;
  }

  const shutdownManager = ShutdownManager.getInstance();
  
  if (!shutdownManager.isShutdownInProgress()) {
    // Prevent immediate quit to allow graceful shutdown
    event.preventDefault();
    
    log("=== Starting Graceful Shutdown ===");
    
    try {
      // Clean up importing documents
      deleteAllCurrentlyImportingDocuments();
      
      // Execute graceful shutdown
      await shutdownManager.shutdown();
      
      log("=== Graceful Shutdown Complete ===");
      
      // Mark shutdown as complete before calling quit
      shutdownComplete = true;
      
      // Now allow the app to quit
      app.quit();
    } catch (error) {
      const errorMessage = error instanceof Error ? error.message : String(error);
      log(`Shutdown error: ${errorMessage}`);
      
      // Mark shutdown as complete even on error
      shutdownComplete = true;
      
      // Force quit even if shutdown fails
      app.quit();
    }
  }
});
